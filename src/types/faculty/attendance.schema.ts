import { z } from 'zod';

// Base Enums
export const BaseAttendanceStatus = z.enum(['present', 'absent', 'leave']);
export const AttendanceSource = z.enum(['self', 'admin', 'biometric', 'system']);
export const VerificationStatus = z.enum(['self_marked', 'admin_verified', 'biometric_verified', 'disputed']);

// Strict ISO Time Formats (Fixing Vulnerability 1)
export const AttendanceModifiers = z.object({
  isLate: z.boolean().default(false),
  isHalfDay: z.boolean().default(false),
  checkInAt: z.string().datetime().optional(), // Strict ISO 8601
  checkOutAt: z.string().datetime().optional(), // Strict ISO 8601
  lateMinutes: z.number().optional()
});

// The Immutable Audit Trail Log (Fixing Vulnerability: Lost Audit History)
export const ChangeLogSchema = z.object({
  editedBy: z.string(), // Employee ID or User ID
  editedAt: z.string().datetime(),
  previousStatus: BaseAttendanceStatus.optional(),
  newStatus: BaseAttendanceStatus,
  reason: z.string().min(5, "Reason is required for audit compliance"),
  source: AttendanceSource
});

// The Financial-Grade Ledger Entry
export const DailyAttendanceRecordSchema = z.object({
  id: z.string().uuid(),
  employeeId: z.string(),
  date: z.string(), // Strict local date YYYY-MM-DD
  
  status: BaseAttendanceStatus,
  modifiers: AttendanceModifiers,
  
  // Security & Identity (Fixing Multi-Actor Trust)
  source: AttendanceSource,
  verificationStatus: VerificationStatus,
  
  // Creation Metadata
  markedBy: z.string(),
  markedAt: z.string().datetime(),
  
  // The Complete History
  changeLogs: z.array(ChangeLogSchema).default([]),
  
  isAutoGeneratedFromLeave: z.boolean().default(false),
});

// The Session Ledger
export const AttendanceSessionSchema = z.object({
  date: z.string(), // YYYY-MM-DD
  status: z.enum(['draft', 'submitted', 'locked']).default('draft'), // Fixing Missing Status
  lockedAt: z.string().datetime().optional(),
  lockedBy: z.string().optional(),
  
  // Snapshots
  totalPresent: z.number().default(0),
  totalAbsent: z.number().default(0),
  totalOnLeave: z.number().default(0),
});

export type AttendanceRecord = z.infer<typeof DailyAttendanceRecordSchema>;
export type AttendanceSession = z.infer<typeof AttendanceSessionSchema>;
export type AttendanceChangeLog = z.infer<typeof ChangeLogSchema>;